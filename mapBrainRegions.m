rawTable.CleanedRegion = strings(numRows, 1);
rawTable.BroadArea = strings(numRows, 1);

for i = 1:numRows
    rawRegion = rawTable.cluster_region(i);
    
    if ismissing(rawRegion) || strlength(rawRegion) == 0
        rawTable.CleanedRegion(i) = "invalid";
        rawTable.BroadArea(i) = "invalid";
        continue;
    end
    
    foundMatch = false;
    
    % exact match check
    if isKey(regionMap, rawRegion)
        fullName = regionMap(rawRegion);
        broadArea = broadAreaMap(rawRegion);
        hemisphere = '';
        if contains(rawRegion, 'R', 'ignorecase', true)
            hemisphere = 'right ';
        elseif contains(rawRegion, 'L', 'ignorecase', true)
            hemisphere = 'left ';
        end
        rawTable.CleanedRegion(i) = strcat(hemisphere, fullName);
        rawTable.BroadArea(i) = broadArea;
        foundMatch = true;
    end
    
    % flexible regex check
    if ~foundMatch
        tokens = regexp(rawRegion, '([RL])([A-Z\-]+)', 'tokens', 'once', 'ignorecase');
        
        if ~isempty(tokens)
            hChar = tokens{1};
            coreAbbr = tokens{2};
            
            if isKey(regionMap, coreAbbr)
                if strcmpi(hChar, 'R')
                    hemisphere = 'right ';
                else
                    hemisphere = 'left ';
                end
                
                rawTable.CleanedRegion(i) = strcat(hemisphere, regionMap(coreAbbr));
                rawTable.BroadArea(i) = broadAreaMap(coreAbbr);
                foundMatch = true;
            end
        end
    end
    
    % fallback for failures
    if ~foundMatch
        rawTable.CleanedRegion(i) = "unknown code";
        rawTable.BroadArea(i) = "unknown";
    end
end

